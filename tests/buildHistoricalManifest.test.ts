import assert from 'node:assert/strict';
import test from 'node:test';
import { buildHistoricalManifest } from '../scripts/lib/buildHistoricalManifest.ts';
import { assertFrozenInventory, frozenInventoryDigest, inventoryCampaignMobiles } from '../scripts/lib/campaignMobileInventory.ts';

test('exact inventory yields two isolated UUIDs; ambiguous identities or financial drift reject', async () => {
  const campaigns = Array.from({ length: 27 }, (_, i) => ({ _id: `id-${i}`, slug: `slug-${i}` }));
  const leads: any[] = Array.from({ length: 691 }, (_, i) => ({ _id: `lead-${i}`, campaignId: 'id-0', clientMobile: String(9000000000 + i), partnerId: 'P1', status: 'PENDING' }));
  leads.push({ _id: 'a', campaignId: 'private-A', clientMobile: '9876543210', partnerId: 'P1', status: 'PENDING' });
  for (let i = 0; i < 9; i++) leads.push({ _id: `b-${i}`, campaignId: 'private-B', clientMobile: '9876543210', partnerId: 'P2', status: 'APPROVED' });
  const before = JSON.stringify({ campaigns, leads });
  const manifest = await buildHistoricalManifest(campaigns, leads, 'synthetic reviewer', 'synthetic approval');
  assert.equal(manifest.expectedTotalLeads, 701);
  assert.deepEqual(manifest.entries.map(e => [e.expectedRecords, e.expectedApproved, e.expectedPaid]), [[1, 0, 0], [9, 9, 0]]);
  assert.notEqual(manifest.entries[0].historicalIdentity, manifest.entries[1].historicalIdentity);
  for (const e of manifest.entries) assert.match(e.historicalIdentity, /^historical:[a-f\d]{8}-[a-f\d]{4}-4[a-f\d]{3}-[89ab][a-f\d]{3}-[a-f\d]{12}$/);
  assert.equal(JSON.stringify({ campaigns, leads }), before);
  const stream = async function* (rows: any[]) { yield* rows; };
  const initial = await inventoryCampaignMobiles(campaigns, stream(leads), manifest);
  const grown = [...leads, { ...leads[0], _id: 'new-lead' }];
  const fresh = await inventoryCampaignMobiles(campaigns, stream(grown), manifest);
  assert.equal(fresh.summary.totalLeads, 702, 'approved historical manifest survives active lead growth');
  const frozen = frozenInventoryDigest(fresh);
  assertFrozenInventory(fresh, frozen);
  assert.notEqual(frozenInventoryDigest(initial), frozen);
  assert.throws(() => assertFrozenInventory(initial, frozen), /Frozen/);
  assert.throws(() => assertFrozenInventory(fresh, undefined), /Frozen/);
  assert.equal((await buildHistoricalManifest(campaigns, leads.slice(22), 'reviewer', 'approval')).expectedTotalLeads, 679);
  await assert.rejects(buildHistoricalManifest(campaigns.slice(1), leads, 'reviewer', 'approval'));
  const changed = structuredClone(leads); changed[700].status = 'PAID';
  await assert.rejects(buildHistoricalManifest(campaigns, changed, 'reviewer', 'approval'));
  changed[700].status = 'APPROVED'; changed[700].campaignId = 'unapproved-third';
  await assert.rejects(buildHistoricalManifest(campaigns, changed, 'reviewer', 'approval'));
  changed[700].campaignId = null;
  await assert.rejects(buildHistoricalManifest(campaigns, changed, 'reviewer', 'approval'));
  const ambiguous = structuredClone(campaigns); ambiguous[1].slug = 'id-0';
  await assert.rejects(buildHistoricalManifest(ambiguous, leads, 'reviewer', 'approval'));
  const replacement = structuredClone(leads); replacement[700]._id = 'replacement-history';
  await assert.rejects(inventoryCampaignMobiles(campaigns, stream(replacement), manifest), /historical records changed/);
  const sameCountChange = structuredClone(leads); sameCountChange[0].partnerId = 'DIFFERENT';
  const changedInventory = await inventoryCampaignMobiles(campaigns, stream(sameCountChange), manifest);
  assert.throws(() => assertFrozenInventory(changedInventory, frozenInventoryDigest(initial)), /Frozen/);
});
